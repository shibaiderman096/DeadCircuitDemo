def review_images(directory, atlas, catalog, frames, report):
    directory.mkdir(parents=True, exist_ok=True)
    atlas.save(directory / 'weapons-native.png')
    atlas.resize((atlas.width * 4, atlas.height * 4), Image.Resampling.NEAREST).save(directory / 'weapons-4x.png')
    # The sprites remain at native size; text and backgrounds are review-only.
    models = ('KA-BAR 1217', 'GLOCK 17', 'Mossberg 590', 'M4A1', 'M24')
    contact = Image.new('RGBA', (740, 144), '#111d20')
    draw = ImageDraw.Draw(contact)
    for i, model in enumerate(models):
        x = i * 148
        draw.text((x + 4, 3), f'{i + 5}: {model}', fill='#eee9d3')
        draw.rectangle((x + 74, 20, x + 145, 142), fill='#ddd5ac')
        for side in (0, 1):
            contact.alpha_composite(frames[f'weapon_icon_{i+5}'], (x + side * 74 + 20, 28))
            contact.alpha_composite(frames[f'weapon_{i+5}'], (x + side * 74 + 4, 86))
    contact.save(directory / 'models-native.png')
    contact.resize((contact.width * 4, contact.height * 4), Image.Resampling.NEAREST).save(directory / 'models-4x.png')
    families = [(f'Muzzle {i}', [f'fx_weapon_muzzle_{i}_{f}' for f in range(3)]) for i in range(6, 10)]
    families += [(k.title(), [f'fx_weapon_{k}_{f}' for f in range(3)]) for k in ('suppressed', 'smoke', 'slash', 'impact')]
    families += [('Debris / glow', ['fx_weapon_casing', 'fx_weapon_shell', 'fx_weapon_glow'])]
    effect = Image.new('RGBA', (440, len(families) * 76), '#111d20')
    ed = ImageDraw.Draw(effect)
    for row, (label, names) in enumerate(families):
        y = row * 76
        ed.text((4, y + 4), label, fill='#eee9d3')
        for f, name in enumerate(names):
            ed.rectangle((222 + f * 72, y + 14, 291 + f * 72, y + 75), fill='#ddd5ac')
            for base in (4, 224):
                frame = frames[name]
                effect.alpha_composite(frame, (base + f * 72, y + 12))
    effect.save(directory / 'effects-native.png')
    effect.resize((effect.width * 4, effect.height * 4), Image.Resampling.NEAREST).save(directory / 'effects-4x.png')
    (directory / 'validation.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')


def generate(review_dir=None):
    import resvg_py

    catalog, source, palette = read_sources()
    with Image.open(io.BytesIO(resvg_py.svg_to_bytes(svg_string=source))) as rendered:
        atlas = rendered.convert('RGBA')
    frames, checks = validate_pixels(atlas, catalog, palette)
    data = dict(width=atlas.width, height=atlas.height,
                sprites=[{k: s[k] for k in FIELDS} for s in catalog['sprites']])
    png = io.BytesIO()
    atlas.save(png, format='PNG', optimize=False, compress_level=9)
    outputs = {'weapons.png': png.getvalue(),
               'weapons.json': (json.dumps(data, indent=2, ensure_ascii=False) + '\n').encode('utf-8')}
    OUT.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        write_changed(OUT / name, content)
    initialize_meta(OUT / 'weapons.png.meta', texture_meta())
    guid = hashlib.md5(b'DeadCircuit/Art/Expansion/weapons.json').hexdigest()
    initialize_meta(OUT / 'weapons.json.meta', f'''fileFormatVersion: 2
guid: {guid}
TextScriptImporter:
  externalObjects: {{}}
  userData:
  assetBundleName:
  assetBundleVariant:
'''.encode('utf-8'))
    # Verify the published files, rather than relying only on the render buffer.
    with Image.open(OUT / 'weapons.png') as published:
        require(published.mode == 'RGBA', 'Published PNG must be RGBA')
        validate_pixels(published, catalog, palette)
    require(json.loads((OUT / 'weapons.json').read_text(encoding='utf-8')) == data, 'Published JSON readback failed')
    report = dict(art_source='existing', route='SVG-authored/code-rendered', imageModelUsed=False,
                  renderer=f'resvg-py {importlib.metadata.version("resvg-py")}',
                  atlasSize=list(atlas.size), sourceSha256=sha256(source.encode('utf-8')),
                  files={name: sha256(content) for name, content in outputs.items()}, **checks)
    if review_dir is not None:
        review_images(Path(review_dir), atlas, catalog, frames, report)
    print(json.dumps({k: v for k, v in report.items() if k != 'frames'}, ensure_ascii=False))
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--review-dir', type=Path, help='Optional native/nearest-neighbor 4x visual review output')
    args = parser.parse_args()
    generate(args.review_dir)
