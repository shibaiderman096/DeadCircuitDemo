"""Render the dedicated weapon atlas from editable, native-grid SVG sources.

Art source: existing icons.svg palette/contours, SVG-authored/code-rendered.
No image model is used. Requires Pillow and resvg-py (reference backend 0.5.0).

    python Tools/generate_weapon_art.py
    python Tools/generate_weapon_art.py --review-dir .forge/weapons-art-review
    python Tools/generate_art.py --weapons-only

Only weapons.png/json and their importer metadata are published. Review images
are opt-in; the normal art generator invokes generate() without review output.
PNG/JSON rectangles use top-left coordinates. Pivots use Unity's bottom-left
normalization: held grip (20,20) on 64x32 => (.3125,.375).
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import io
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from PIL import Image, ImageChops, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Tools/weapon-art'
OUT = ROOT / 'Assets/DeadCircuit/Resources/Art/Expansion'
SVG = '{http://www.w3.org/2000/svg}'
FIELDS = ('name', 'x', 'y', 'w', 'h', 'pixelsPerUnit', 'pivotX', 'pivotY')
MUZZLES = {5: (58, 16), 6: (45, 14), 7: (61, 14), 8: (60, 14), 9: (62, 14)}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def write_changed(path, data):
    """Avoid unnecessary Unity imports when generated bytes have not changed."""
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def initialize_meta(path, data):
    """Seed GUID/importer once; preserve subsequent Unity normalization/settings."""
    try:
        with path.open('xb') as stream:
            stream.write(data)
    except FileExistsError:
        pass


def expected_names():
    return ({f'weapon_icon_{i}' for i in MUZZLES}
            | {f'weapon_{i}' for i in MUZZLES}
            | {f'fx_weapon_muzzle_{i}_{f}' for i in range(6, 10) for f in range(3)}
            | {f'fx_weapon_{kind}_{f}' for kind in ('suppressed', 'smoke', 'slash', 'impact') for f in range(3)}
            | {'fx_weapon_casing', 'fx_weapon_shell', 'fx_weapon_glow'})


def check_geometry(element, w, h):
    tag = element.tag.removeprefix(SVG)
    require(tag in ('rect', 'path', 'title'), f'Unsupported SVG element: {tag}')
    if tag == 'title':
        return
    require(set(element.attrib) <= ({'class', 'x', 'y', 'width', 'height'} if tag == 'rect' else {'class', 'd'}),
            f'Unexpected geometry attributes: {element.attrib}')
    if tag == 'rect':
        values = [element.get(k, '') for k in ('x', 'y', 'width', 'height')]
        require(all(re.fullmatch(r'\d+', v) for v in values), 'Rectangles must use integer pixels')
        x, y, rw, rh = map(int, values)
        require(rw > 0 and rh > 0 and 1 <= x and x + rw <= w - 1 and 1 <= y and y + rh <= h - 1,
                f'Rectangle escapes its padded {w}x{h} frame: {values}')
        return
    # Authored paths deliberately use only absolute orthogonal commands.
    path = element.get('d', '')
    require(re.fullmatch(r'[MHVZ\d\s-]+', path) is not None, 'Use integer M/H/V/Z SVG paths only')
    tokens = re.findall(r'[MHVZ]|-?\d+', path)
    i, x, y = 0, 0, 0
    while i < len(tokens):
        command = tokens[i]
        i += 1
        if command == 'Z':
            continue
        require(command in ('M', 'H', 'V'), 'Malformed orthogonal SVG path')
        if command == 'M':
            x, y = int(tokens[i]), int(tokens[i + 1])
            i += 2
        elif command == 'H':
            x = int(tokens[i])
            i += 1
        else:
            y = int(tokens[i])
            i += 1
        require(1 <= x <= w - 1 and 1 <= y <= h - 1, f'Path escapes padded {w}x{h} frame: {(x, y)}')


def read_sources():
    catalog = json.loads((SOURCE / 'weapons.catalog.json').read_text(encoding='utf-8'))
    text = (SOURCE / 'weapons.svg').read_text(encoding='utf-8')
    root = ET.fromstring(text)
    width, height = catalog['width'], catalog['height']
    require(root.tag == SVG + 'svg' and root.get('width') == str(width) and root.get('height') == str(height)
            and root.get('viewBox') == f'0 0 {width} {height}' and root.get('shape-rendering') == 'crispEdges',
            'SVG dimensions/viewBox/crispEdges differ from the catalog')
    require(catalog['art_source'] == 'existing', 'This atlas must retain existing-art provenance')
    reference = (ROOT / catalog['reference']).read_text(encoding='utf-8')
    reference_colors = set(re.findall(r'#[0-9a-fA-F]{6}', reference))
    palette = set(catalog['palette'].values())
    require(palette <= reference_colors, 'Weapon colors must belong to the existing icons.svg palette')
    styles = root.findall(SVG + 'style')
    require(len(styles) == 1, 'Exactly one flat palette style is required')
    classes = dict(re.findall(r'\.([a-z-]+)\{fill:(#[0-9a-f]{6})\}', styles[0].text or ''))
    require(set(classes.values()) <= palette, 'SVG styles escape the catalog palette')
    require(re.sub(r'\.([a-z-]+)\{fill:(#[0-9a-f]{6})\}', '', styles[0].text or '').strip() == '',
            'Only literal flat fill classes are permitted')
    sprites = catalog['sprites']
    names = [s['name'] for s in sprites]
    require(len(names) == len(set(names)) and set(names) == expected_names(), 'Weapon key contract mismatch/duplicates')
    groups = root.findall(SVG + 'g')
    require(len(groups) == len(sprites) and [g.get('id') for g in groups] == names, 'SVG/catalog group order differs')
    require(all(e.tag in (SVG + 'g', SVG + 'style', SVG + 'title', SVG + 'desc') for e in root),
            'No external resources, raster images, text, filters or gradients are allowed')
    rectangles = []
    for s, group in zip(sprites, groups):
        require(all(type(s[k]) is int for k in ('x', 'y', 'w', 'h', 'pixelsPerUnit')), 'Atlas coordinates must be integer')
        x, y, w, h = (s[k] for k in ('x', 'y', 'w', 'h'))
        require(0 <= x and 0 <= y and x + w <= width and y + h <= height, f'{s["name"]}: atlas bounds')
        require(s['pixelsPerUnit'] == 32 and 0 <= s['pivotX'] <= 1 and 0 <= s['pivotY'] <= 1, 'Invalid PPU/pivot')
        require(group.attrib == {'id': s['name'], 'transform': f'translate({x} {y})'}, 'Only integer translation is allowed')
        for child in group:
            check_geometry(child, w, h)
            if child.tag != SVG + 'title':
                require(child.get('class') in classes, f'Unknown palette class: {child.get("class")}')
        for ox, oy, ow, oh in rectangles:
            require(x + w <= ox or ox + ow <= x or y + h <= oy or oy + oh <= y, 'Atlas frame overlap')
        rectangles.append((x, y, w, h))
        if s['name'].startswith('weapon_icon_'):
            require((w, h, s['pivotX'], s['pivotY']) == (32, 32, .5, .5), 'Inventory frame contract')
        elif s['name'].startswith('weapon_'):
            wid = int(s['name'].removeprefix('weapon_'))
            require((w, h, s['pivotX'], s['pivotY']) == (64, 32, .3125, .375), 'Held frame/grip contract')
            require(s['gripSource'] == [20, 20] and tuple(s['muzzleSource']) == MUZZLES[wid], 'Held registration contract')
        elif s['name'].startswith(('fx_weapon_muzzle_', 'fx_weapon_suppressed_')):
            require((w, h, s['pivotX'], s['pivotY']) == (64, 32, .0625, .5), 'Muzzle registration contract')
            require(s['emissionSource'] == [4, 16], 'Muzzle emission source contract')
        else:
            size = 16 if s['name'] in ('fx_weapon_casing', 'fx_weapon_shell') else 32 if s['name'].startswith('fx_weapon_impact_') else 64
            require((w, h, s['pivotX'], s['pivotY']) == (size, size, .5, .5), 'Centered effect frame contract')
    # Check the actual published catalogs, including legacy width/height schemas.
    for other in sorted((ROOT / 'Assets/DeadCircuit/Resources/Art').rglob('*.json')):
        if other == OUT / 'weapons.json':
            continue
        data = json.loads(other.read_text(encoding='utf-8-sig'))
        other_names = {s.get('name') for s in data.get('sprites', [])} if isinstance(data, dict) else set()
        require(not (set(names) & other_names), f'Weapon keys collide with {other.relative_to(ROOT)}')
    return catalog, text, palette


def validate_pixels(atlas, catalog, palette):
    require(atlas.size == (catalog['width'], catalog['height']), 'Rendered PNG size mismatch')
    require(sum(atlas.getchannel('A').histogram()[1:255]) == 0, 'Partial alpha is forbidden')
    colors = {rgb[:3] for count, rgb in atlas.getcolors(atlas.width * atlas.height) if rgb[3]}
    allowed = {tuple(bytes.fromhex(c[1:])) for c in palette}
    require(colors <= allowed and len(colors) <= 20, f'PNG palette drift: {colors - allowed}')
    occupied = Image.new('L', atlas.size)
    frames, checks = {}, []
    for s in catalog['sprites']:
        x, y, w, h = (s[k] for k in ('x', 'y', 'w', 'h'))
        frame = atlas.crop((x, y, x + w, y + h))
        bbox = frame.getbbox()
        require(bbox is not None, f'{s["name"]}: empty frame')
        padding = min(bbox[0], bbox[1], w - bbox[2], h - bbox[3])
        require(padding >= 1, f'{s["name"]}: missing transparent padding')
        if s['name'].startswith('weapon_') and not s['name'].startswith('weapon_icon_'):
            require(frame.getpixel((20, 20))[3] == 255, f'{s["name"]}: grip must touch visible art')
            mx, my = s['muzzleSource']
            require(any(frame.getpixel((mx + dx, my))[3] for dx in (-1, 0)), f'{s["name"]}: muzzle is detached')
        if s['name'].startswith(('fx_weapon_muzzle_', 'fx_weapon_suppressed_')):
            require(bbox[0] == 4 and frame.getpixel((4, 16))[3] == 255, f'{s["name"]}: emission anchor drift')
        frames[s['name']] = frame
        occupied.paste(255, (x, y, x + w, y + h))
        checks.append(dict(name=s['name'], bbox=list(bbox), padding=padding,
                           opaquePixels=frame.getchannel('A').histogram()[255], sha256=sha256(frame.tobytes())))
    require(ImageChops.subtract(atlas.getchannel('A'), occupied).getbbox() is None, 'Pixels spill outside catalog frames')
    for prefix in ([f'fx_weapon_muzzle_{i}' for i in range(6, 10)]
                   + ['fx_weapon_suppressed', 'fx_weapon_smoke', 'fx_weapon_slash', 'fx_weapon_impact']):
        require(len({sha256(frames[f'{prefix}_{f}'].tobytes()) for f in range(3)}) == 3, f'{prefix}: repeated frames')
    return frames, dict(spriteCount=len(frames), partialAlphaPixels=0, offPalettePixels=0,
                        usedColorCount=len(colors), minPadding=min(s['padding'] for s in checks), frames=checks)


