"""Render the UI-only equipment atlas from editable native-grid SVG art.

Art source: existing icons.svg palette and weapons.svg style; SVG-authored/
code-rendered, without an image model. Requires Pillow and resvg-py.

    python Tools/generate_equipment_art.py
    python Tools/generate_equipment_art.py --review-dir .forge/equipment-art-review

The public integration entry point is generate(review_dir=None). Published
rectangles use top-left coordinates, 32 PPU and centered Unity pivots. This
module never modifies the legacy icons, wearable layers or weapon attachments.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import io
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from PIL import Image, ImageChops, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Tools/equipment-art'
OUT = ROOT / 'Assets/DeadCircuit/Resources/Art/Expansion'
SVG = '{http://www.w3.org/2000/svg}'
FIELDS = ('name', 'x', 'y', 'w', 'h', 'pixelsPerUnit', 'pivotX', 'pivotY')
EXPECTED = tuple(f'equipment_icon_gear_{i}' for i in (*range(5), *range(10, 19))) + tuple(
    f'equipment_icon_part_{i}' for i in range(7))


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def write_changed(path, data):
    """Avoid repeated Unity imports when generated bytes are unchanged."""
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def initialize_meta(path, data):
    """Initialize missing metadata only; retain Unity-normalized importers."""
    try:
        with path.open('xb') as stream:
            stream.write(data)
    except FileExistsError:
        pass


def check_geometry(element, classes):
    tag = element.tag.removeprefix(SVG)
    if tag == 'title':
        require(not element.attrib and not list(element), 'Invalid sprite title')
        return
    require(tag in ('rect', 'path'), f'Unsupported SVG geometry: {tag}')
    allowed = {'class', 'x', 'y', 'width', 'height'} if tag == 'rect' else {'class', 'd'}
    require(set(element.attrib) == allowed, f'Unexpected SVG attributes: {element.attrib}')
    require(element.get('class') in classes, 'Unknown palette class')
    if tag == 'rect':
        values = [element.get(k, '') for k in ('x', 'y', 'width', 'height')]
        require(all(re.fullmatch(r'[0-9]+', v) for v in values), 'Rectangles must use integer pixels')
        x, y, w, h = map(int, values)
        require(w > 0 and h > 0 and 1 <= x < x + w <= 31 and 1 <= y < y + h <= 31,
                f'Rectangle escapes the padded 32x32 cell: {values}')
        return
    path = element.get('d', '')
    require(re.fullmatch(r'[MHVZ0-9 ]+', path) is not None, 'Use absolute integer M/H/V/Z paths')
    tokens = re.findall(r'[MHVZ]|[0-9]+', path)
    i, x, y, start = 0, 0, 0, None
    closed = True
    while i < len(tokens):
        command = tokens[i]
        i += 1
        require(command in ('M', 'H', 'V', 'Z'), 'Malformed SVG path')
        if command == 'Z':
            require(start is not None and (x == start[0] or y == start[1]),
                    'Path closure must also follow the integer orthogonal grid')
            x, y = start
            closed = True
            continue
        if command == 'M':
            require(closed, 'Every subpath must be closed')
            x, y = int(tokens[i]), int(tokens[i + 1])
            i += 2
            start, closed = (x, y), False
        else:
            require(not closed, 'Path segment outside a subpath')
            if command == 'H':
                x = int(tokens[i])
            else:
                y = int(tokens[i])
            i += 1
        require(1 <= x <= 31 and 1 <= y <= 31, f'Path escapes the padded cell: {(x, y)}')
    require(closed and start is not None, 'Unclosed or empty SVG path')


def read_sources():
    catalog = json.loads((SOURCE / 'equipment.catalog.json').read_text(encoding='utf-8'))
    source = (SOURCE / 'equipment.svg').read_text(encoding='utf-8')
    root = ET.fromstring(source)
    width, height = catalog['width'], catalog['height']
    require(type(width) is int and type(height) is int and (width, height) == (240, 104),
            'Equipment atlas must use the 7x3, 32-cell/2-gutter layout')
    require(root.tag == SVG + 'svg' and root.attrib == dict(
        width=str(width), height=str(height), viewBox=f'0 0 {width} {height}',
        **{'shape-rendering': 'crispEdges'}), 'SVG dimensions/grid/crispEdges mismatch')
    require(catalog['art_source'] == 'existing' and catalog['route'] == 'SVG-authored/code-rendered',
            'Preserve the declared existing-art provenance')
    reference = (ROOT / catalog['reference']).read_text(encoding='utf-8')
    style_reference = (ROOT / catalog['styleReference']).read_text(encoding='utf-8')
    require(catalog['referenceSha256'] == sha256(reference.encode('utf-8')), 'Existing-art reference drift')
    palette = set(catalog['palette'].values())
    require(0 < len(palette) <= 24 and palette <= set(re.findall(r'#[0-9a-f]{6}', reference))
            and palette <= set(re.findall(r'#[0-9a-f]{6}', style_reference)),
            'Palette must stay within the existing compact weapon/icon palette')
    styles = root.findall(SVG + 'style')
    require(len(styles) == 1, 'Exactly one palette style is required')
    css = styles[0].text or ''
    pattern = r'[.]([a-z-]+)[{]fill:(#[0-9a-f]{6})[}]'
    classes = dict(re.findall(pattern, css))
    require(classes == {f'c-{key}': color for key, color in catalog['palette'].items()}
            and not re.sub(pattern, '', css).strip(), 'Only catalog flat-fill classes are allowed')
    require(all(e.tag in (SVG + 'style', SVG + 'title', SVG + 'desc', SVG + 'g') for e in root),
            'External resources, text, gradients and filters are forbidden')
    sprites, groups = catalog['sprites'], root.findall(SVG + 'g')
    names = [s['name'] for s in sprites]
    require(tuple(names) == EXPECTED and len(set(names)) == 21, 'Equipment key/order/uniqueness contract')
    require([g.get('id') for g in groups] == names, 'SVG/catalog groups differ')
    rectangles = []
    for i, (s, group) in enumerate(zip(sprites, groups)):
        require(all(type(s[k]) is int for k in ('x', 'y', 'w', 'h', 'pixelsPerUnit')),
                'Coordinates and PPU must be integers')
        x, y, w, h = (s[k] for k in ('x', 'y', 'w', 'h'))
        require((x, y, w, h) == (2 + i % 7 * 34, 2 + i // 7 * 34, 32, 32), 'Cell/gutter layout drift')
        require((s['pixelsPerUnit'], s['pivotX'], s['pivotY']) == (32, .5, .5), 'UI PPU/pivot contract')
        require(group.attrib == {'id': s['name'], 'transform': f'translate({x} {y})'},
                'Only the catalog integer translation is allowed')
        for child in group:
            check_geometry(child, classes)
        for ox, oy, ow, oh in rectangles:
            require(x + w + 2 <= ox or ox + ow + 2 <= x or y + h + 2 <= oy or oy + oh + 2 <= y,
                    'Cells require at least 2px transparent gutter')
        rectangles.append((x, y, w, h))
    for other in sorted((ROOT / 'Assets/DeadCircuit/Resources/Art').rglob('*.json')):
        if other == OUT / 'equipment-icons.json':
            continue
        data = json.loads(other.read_text(encoding='utf-8-sig'))
        other_names = {s.get('name') for s in data.get('sprites', [])} if isinstance(data, dict) else set()
        require(not (set(names) & other_names), f'Keys collide with {other.relative_to(ROOT)}')
    return catalog, source, palette


def validate_pixels(atlas, catalog, palette):
    require(atlas.mode == 'RGBA' and atlas.size == (catalog['width'], catalog['height']), 'PNG format/size drift')
    require(sum(atlas.getchannel('A').histogram()[1:255]) == 0, 'Partial alpha is forbidden')
    colors = {color[:3] for count, color in atlas.getcolors(atlas.width * atlas.height) if color[3]}
    allowed = {tuple(bytes.fromhex(c[1:])) for c in palette}
    require(colors <= allowed and len(colors) <= 24, 'Off-palette colors or palette overflow')
    occupied = Image.new('L', atlas.size)
    frames, checks = {}, []
    for s in catalog['sprites']:
        x, y, w, h = (s[k] for k in ('x', 'y', 'w', 'h'))
        frame = atlas.crop((x, y, x + w, y + h))
        bbox = frame.getbbox()
        require(bbox is not None, f'{s["name"]}: empty icon')
        padding = min(bbox[0], bbox[1], w - bbox[2], h - bbox[3])
        require(padding >= 1, f'{s["name"]}: missing internal padding')
        frames[s['name']] = frame
        occupied.paste(255, (x, y, x + w, y + h))
        checks.append(dict(name=s['name'], bbox=list(bbox), padding=padding,
                           opaquePixels=frame.getchannel('A').histogram()[255], sha256=sha256(frame.tobytes())))
    require(ImageChops.subtract(atlas.getchannel('A'), occupied).getbbox() is None, 'Gutter or exterior pixel spill')
    require(len({s['sha256'] for s in checks}) == 21, 'Duplicated icon artwork')
    return frames, dict(spriteCount=len(frames), partialAlphaPixels=0, offPalettePixels=0, gutterPixels=2,
                        usedColorCount=len(colors), minPadding=min(s['padding'] for s in checks), frames=checks)


