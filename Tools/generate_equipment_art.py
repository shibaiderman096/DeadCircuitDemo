def review_images(directory, atlas, catalog, frames, report):
    directory.mkdir(parents=True, exist_ok=True)
    atlas.save(directory / 'equipment-atlas-native.png')
    atlas.resize((atlas.width * 4, atlas.height * 4), Image.Resampling.NEAREST).save(
        directory / 'equipment-atlas-4x.png')
    font = ImageFont.load_default(size=10)
    for scale in (1, 4):
        cell_w, cell_h = 200, 82 if scale == 1 else 184
        for background, color, foreground in (('dark', '#111d20', '#eee9d3'), ('light', '#ddd5ac', '#192829')):
            contact = Image.new('RGBA', (7 * cell_w, 28 + 3 * cell_h), color)
            draw = ImageDraw.Draw(contact)
            draw.text((8, 6), f'Equipment UI icons | {scale}x nearest | {background} | 21 unique keys',
                      font=font, fill=foreground)
            for i, sprite in enumerate(catalog['sprites']):
                x, y = i % 7 * cell_w, 28 + i // 7 * cell_h
                draw.text((x + 6, y + 2), sprite['name'], font=font, fill=foreground)
                draw.text((x + 6, y + 15), sprite['label'], font=font, fill=foreground)
                frame = frames[sprite['name']]
                if scale != 1:
                    frame = frame.resize((32 * scale, 32 * scale), Image.Resampling.NEAREST)
                contact.alpha_composite(frame, (x + (cell_w - frame.width) // 2, y + 34))
            contact.save(directory / f'equipment-{scale}x-{background}.png')
    (directory / 'validation.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')


def generate(review_dir=None):
    import resvg_py

    catalog, source, palette = read_sources()
    with Image.open(io.BytesIO(resvg_py.svg_to_bytes(svg_string=source))) as rendered:
        atlas = rendered.convert('RGBA')
    frames, checks = validate_pixels(atlas, catalog, palette)
    data = dict(width=atlas.width, height=atlas.height,
                sprites=[{key: sprite[key] for key in FIELDS} for sprite in catalog['sprites']])
    png = io.BytesIO()
    atlas.save(png, format='PNG', optimize=False, compress_level=9)
    outputs = {'equipment-icons.png': png.getvalue(),
               'equipment-icons.json': (json.dumps(data, indent=2) + '\n').encode('utf-8')}
    OUT.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        write_changed(OUT / name, content)
    initialize_meta(OUT / 'equipment-icons.png.meta', texture_meta())
    guid = hashlib.md5(b'DeadCircuit/Art/Expansion/equipment-icons.json').hexdigest()
    initialize_meta(OUT / 'equipment-icons.json.meta', f'''fileFormatVersion: 2
guid: {guid}
TextScriptImporter:
  externalObjects: {{}}
  userData:
  assetBundleName:
  assetBundleVariant:
'''.encode('utf-8'))
    with Image.open(OUT / 'equipment-icons.png') as published:
        validate_pixels(published, catalog, palette)
    require(json.loads((OUT / 'equipment-icons.json').read_text(encoding='utf-8')) == data, 'JSON readback failed')
    report = dict(art_source='existing', route='SVG-authored/code-rendered', imageModelUsed=False,
                  renderer=f'resvg-py {importlib.metadata.version("resvg-py")}', atlasSize=list(atlas.size),
                  sourceSha256=sha256(source.encode('utf-8')),
                  files={name: sha256(content) for name, content in outputs.items()}, **checks)
    if review_dir is not None:
        review_images(Path(review_dir), atlas, catalog, frames, report)
    print(json.dumps({key: value for key, value in report.items() if key != 'frames'}))
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--review-dir', type=Path, help='Optional native/4x dark and light named previews')
    args = parser.parse_args()
    generate(args.review_dir)
